def get_commodity_meta(code: str) -> Dict[str, Any]:
    key = (code or "").strip().upper()
    info = COMMODITIES.get(key)
    aliases = SEARCH_ALIASES.get(key, "")
    if info:
        return {
            "code": key,
            "en": info["en"],
            "kn": info["kn"],
            "group": info["group"],
            "group_kn": GROUPS_KN.get(info["group"], info["group"]),
            "aliases": aliases,
        }
    return {
        "code": key,
        "en": key.title(),
        "kn": key.title(),
        "group": "Commercial",
        "group_kn": GROUPS_KN["Commercial"],
        "aliases": aliases,
    }


def get_market_meta(market_code: str, district: str = "") -> Dict[str, str]:
    code = (market_code or "").strip().upper()
    clean_dist = (district or "").replace("•", "").strip()
    dist_title = clean_dist.title() if clean_dist else ""
    if dist_title == "Mandya":
        dist_title = "Mandya"
    return {
        "code": code,
        "en": f"APMC, {code}" if not code.startswith("APMC") else code,
        "kn": f"ಎಪಿಎಂಸಿ, {MARKETS_KN.get(code, code)}",
        "short_kn": MARKETS_KN.get(code, code),
        "district_en": dist_title,
        "district_kn": DISTRICTS_KN.get(dist_title, dist_title),
    }

